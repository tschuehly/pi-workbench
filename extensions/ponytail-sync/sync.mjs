#!/usr/bin/env node
// Regenerate the ponytail block in <agent-dir>/APPEND_SYSTEM.md from the installed ponytail package.
// Static text keeps the system prompt byte-stable, unlike the package extension's per-turn injection.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { homedir } from "node:os";
import { join } from "node:path";

const agentDir = process.env.PI_CODING_AGENT_DIR || join(homedir(), ".pi", "agent");
const pkg = join(agentDir, "git", "github.com", "DietrichGebert", "ponytail");
const target = join(agentDir, "APPEND_SYSTEM.md");
const BEGIN = "<!-- ponytail-sync:begin (generated by ~/.pi/agent/bin/ponytail-sync; do not edit) -->";
const END = "<!-- ponytail-sync:end -->";

const { getPonytailInstructions } = createRequire(import.meta.url)(join(pkg, "hooks", "ponytail-instructions.js"));
const text = getPonytailInstructions("full");
// The package silently falls back to a short text if SKILL.md is unreadable; refuse that.
if (!text.includes("\n# Ponytail")) throw new Error(`ponytail SKILL.md not found under ${pkg}`);
const block = `${BEGIN}\n${text.trim()}\n${END}`;

const old = existsSync(target) ? readFileSync(target, "utf8") : "";
const start = old.indexOf(BEGIN);
const end = old.indexOf(END);
let next;
if (start >= 0 && end > start) next = old.slice(0, start) + block + old.slice(end + END.length);
else if (start >= 0 || end >= 0) throw new Error(`unbalanced ponytail markers in ${target}`);
else next = old.trim() ? `${old.trimEnd()}\n\n${block}\n` : `${block}\n`;

if (next === old) console.log(`ponytail-sync: ${target} already current`);
else {
  writeFileSync(target, next);
  console.log(`ponytail-sync: updated ${target} (${text.length} chars of ponytail text)`);
}
