import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { test } from "node:test";
import ponytailSyncExtension from "./index.ts";

const SYNC = fileURLToPath(new URL("./sync.mjs", import.meta.url));
const BEGIN = "<!-- ponytail-sync:begin (generated by ~/.pi/agent/bin/ponytail-sync; do not edit) -->";
const END = "<!-- ponytail-sync:end -->";

// A fake installed package shaped like DietrichGebert/ponytail: the hook reads SKILL.md or falls back.
function agentDir(skill) {
  const dir = mkdtempSync(join(process.env.PI_TMP || tmpdir(), "ponytail-sync-"));
  const pkg = join(dir, "git", "github.com", "DietrichGebert", "ponytail");
  mkdirSync(join(pkg, "hooks"), { recursive: true });
  mkdirSync(join(pkg, "skills", "ponytail"), { recursive: true });
  writeFileSync(join(pkg, "hooks", "ponytail-instructions.js"), `const fs = require("fs"), path = require("path");
exports.getPonytailInstructions = (mode) => { try { return "PONYTAIL " + mode + "\\n\\n" + fs.readFileSync(path.join(__dirname, "..", "skills", "ponytail", "SKILL.md"), "utf8"); } catch { return "PONYTAIL fallback"; } };`);
  if (skill) writeFileSync(join(pkg, "skills", "ponytail", "SKILL.md"), skill);
  return dir;
}
const sync = (dir) => spawnSync(process.execPath, [SYNC], { env: { ...process.env, PI_CODING_AGENT_DIR: dir }, encoding: "utf8" });

test("replaces a stale block, keeps the rest of APPEND_SYSTEM.md, and is idempotent", () => {
  const dir = agentDir("# Ponytail\n\nnew rules\n");
  const file = join(dir, "APPEND_SYSTEM.md");
  writeFileSync(file, `before\n${BEGIN}\nold rules\n${END}\nafter\n`);
  assert.equal(sync(dir).status, 0);
  assert.equal(readFileSync(file, "utf8"), `before\n${BEGIN}\nPONYTAIL full\n\n# Ponytail\n\nnew rules\n${END}\nafter\n`);
  const again = sync(dir);
  assert.equal(again.status, 0);
  assert.match(again.stdout, /already current/);
  rmSync(dir, { recursive: true });
});

test("refuses to write when SKILL.md is unreadable", () => {
  const dir = agentDir(null);
  const file = join(dir, "APPEND_SYSTEM.md");
  const original = `${BEGIN}\nold rules\n${END}\n`;
  writeFileSync(file, original);
  assert.notEqual(sync(dir).status, 0);
  assert.equal(readFileSync(file, "utf8"), original);
  rmSync(dir, { recursive: true });
});

test("lead sessions run the sync at session start; child processes never do", async () => {
  const calls = [];
  const handlers = {};
  const pi = { on: (event, handler) => { handlers[event] = handler; }, exec: async (...args) => { calls.push(args); throw new Error("boom"); } };
  const kind = process.env.PI_WORKBENCH_EXECUTION_KIND;
  process.env.PI_WORKBENCH_EXECUTION_KIND = "subagent";
  ponytailSyncExtension(pi);
  assert.equal(handlers.session_start, undefined);
  delete process.env.PI_WORKBENCH_EXECUTION_KIND;
  ponytailSyncExtension(pi);
  handlers.session_start({ reason: "startup" }, {});
  await new Promise((resolve) => setImmediate(resolve));
  if (kind !== undefined) process.env.PI_WORKBENCH_EXECUTION_KIND = kind;
  assert.deepEqual(calls.map(([cmd, args]) => [cmd, args]), [["node", [SYNC]]]);
});
