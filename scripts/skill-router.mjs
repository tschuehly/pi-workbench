#!/usr/bin/env node
// Collapse a skill bundle into one router skill: Pi stops skill discovery at a directory that holds
// SKILL.md, so a root SKILL.md hides every nested skill from the startup list; INDEX.md, read on
// demand, names each one and its path. Usage: node scripts/skill-router.mjs <bundle-dir> [--description "..."]
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { basename, join, relative, resolve } from "node:path";

const MARKER = "<!-- generated by pi-workbench scripts/skill-router.mjs; rerun it after updating the bundle -->";

// shortcut: one-line `key: value` frontmatter only (plain, "double" or 'single' quoted); fails on block scalars.
function field(text, key, file) {
  const fm = text.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? "";
  const raw = fm.match(new RegExp(`^${key}:[ \\t]*(.*)$`, "m"))?.[1].trim();
  if (!raw) return undefined;
  if (/^[>|]/.test(raw)) throw new Error(`${file}: block-scalar ${key} is not supported`);
  if (raw.startsWith('"')) return JSON.parse(raw);
  if (raw.startsWith("'")) return raw.slice(1, -1).replaceAll("''", "'");
  return raw;
}

function findSkills(dir, root, out = []) {
  for (const entry of readdirSync(dir)) {
    if (entry.startsWith(".") || entry === "node_modules") continue;
    const path = join(dir, entry);
    if (!statSync(path).isDirectory()) continue;
    const file = join(path, "SKILL.md");
    if (existsSync(file)) out.push(file);
    else findSkills(path, root, out);
  }
  return out;
}

const args = process.argv.slice(2);
const dir = resolve(args[0] ?? "");
if (!args[0] || !statSync(dir, { throwIfNoEntry: false })?.isDirectory()) {
  console.error("usage: skill-router.mjs <bundle-dir> [--description \"...\"]");
  process.exit(2);
}
const routerFile = join(dir, "SKILL.md");
if (existsSync(routerFile) && !readFileSync(routerFile, "utf8").includes(MARKER)) {
  console.error(`${routerFile} exists and was not written by skill-router; move it first`);
  process.exit(1);
}

const plugin = join(dir, ".claude-plugin", "plugin.json");
const meta = existsSync(plugin) ? JSON.parse(readFileSync(plugin, "utf8")) : {};
const di = args.indexOf("--description");
const summary = di > 0 ? args[di + 1] : meta.description;
if (!summary) {
  console.error("no .claude-plugin/plugin.json description; pass --description \"what the bundle covers\"");
  process.exit(2);
}

const skills = findSkills(dir, dir).map((file) => {
  const text = readFileSync(file, "utf8");
  const description = field(text, "description", file);
  if (!description) throw new Error(`${file}: no description`);
  return { name: field(text, "name", file) ?? basename(join(file, "..")), description, path: relative(dir, file) };
}).sort((a, b) => a.name.localeCompare(b.name));
if (skills.length === 0) throw new Error(`no nested SKILL.md under ${dir}`);

const name = meta.name ?? basename(dir);
// A trial answered from memory while the description only named the bundle; say when to load it.
const description = `${summary.replace(/\s+$/, "")} Load this before answering any such question from memory: it routes to the matching one of ${skills.length} specialised skills.`;
writeFileSync(routerFile, `---
name: ${name}
description: ${JSON.stringify(description)}
---

${MARKER}

# ${name}

This bundle holds ${skills.length} skills. They are not in the startup skill list; pick one here.

1. Search \`INDEX.md\` (beside this file) for the task's keywords, e.g. \`grep -i rechnung INDEX.md\`,
   or read it whole. Each line is \`name\` (path): description.
2. Read the best match's \`SKILL.md\` (path relative to this directory) and follow it. Read a second
   one only when the task clearly spans two.
3. If nothing matches, say so and work without the bundle.
`);
writeFileSync(join(dir, "INDEX.md"), `${MARKER}\n\n# ${name}: skill index\n\n${skills.map((s) => `- \`${s.name}\` (${s.path}): ${s.description}`).join("\n")}\n`);
console.log(`${routerFile}: router for ${skills.length} skills; index in INDEX.md`);
